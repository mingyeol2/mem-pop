export function buildUserPrompt(keyword: string): string {
  return `외우고 싶은 키워드: "${keyword}"\n위 키워드에 대해 가장 기발하고 뇌리에 박히는 1~2줄 핵심 배경(summary), 3줄 연상 암기 스토리(story)와 3지선다 1초 퀴즈(quiz)를 요구된 순수 JSON 스키마로 생성해 주세요.`;
}

